def init_db():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    c.executescript("""
        DROP TABLE IF EXISTS car_catalog_bodies;
        DROP TABLE IF EXISTS car_catalog_generations;
        DROP TABLE IF EXISTS car_catalog_models;
        DROP TABLE IF EXISTS car_catalog_makes;
        
        CREATE TABLE car_catalog_makes (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            slug TEXT UNIQUE NOT NULL,
            name TEXT NOT NULL
        );
        CREATE TABLE car_catalog_models (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            make_id INTEGER NOT NULL,
            slug TEXT NOT NULL,
            name TEXT NOT NULL,
            UNIQUE(make_id, slug),
            FOREIGN KEY (make_id) REFERENCES car_catalog_makes(id)
        );
        CREATE TABLE car_catalog_generations (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            model_id INTEGER NOT NULL,
            name TEXT NOT NULL,
            year_from INTEGER,
            year_to INTEGER,
            UNIQUE(model_id, name, year_from),
            FOREIGN KEY (model_id) REFERENCES car_catalog_models(id)
        );
        CREATE TABLE car_catalog_bodies (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            generation_id INTEGER NOT NULL,
            body_type TEXT NOT NULL,
            frames TEXT,
            drom_id TEXT,
            FOREIGN KEY (generation_id) REFERENCES car_catalog_generations(id)
        );
        CREATE INDEX idx_bodies_generation ON car_catalog_bodies(generation_id);
        CREATE INDEX idx_generations_model ON car_catalog_generations(model_id);
        CREATE INDEX idx_models_make ON car_catalog_models(make_id);
    """)
    conn.commit()
    conn.close()


def seed():
    init_db()
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()

    total_makes = 0
    total_models = 0
    total_gens = 0
    total_bodies = 0

    for make_name, models in SEED_DATA:
        slug = make_name.lower().replace(" ", "_").replace("(", "").replace(")", "").replace(".", "")
        c.execute("INSERT INTO car_catalog_makes (slug, name) VALUES (?, ?)", (slug, make_name))
        make_id = c.lastrowid
        total_makes += 1

        for model_name, generations in models:
            model_slug = model_name.lower().replace(" ", "_").replace("-", "_")
            c.execute("INSERT INTO car_catalog_models (make_id, slug, name) VALUES (?, ?, ?)",
                      (make_id, model_slug, model_name))
            model_id = c.lastrowid
            total_models += 1

            for gen_name, year_from, year_to, bodies in generations:
                c.execute(
                    "INSERT INTO car_catalog_generations (model_id, name, year_from, year_to) VALUES (?, ?, ?, ?)",
                    (model_id, gen_name, year_from, year_to))
                gen_id = c.lastrowid
                total_gens += 1

                for body in bodies:
                    c.execute(
                        "INSERT INTO car_catalog_bodies (generation_id, body_type, frames, drom_id) VALUES (?, ?, ?, ?)",
                        (gen_id, body, None, None))
                    total_bodies += 1

    conn.commit()
    conn.close()

    print(f"Seeded {total_makes} makes, {total_models} models, {total_gens} generations, {total_bodies} bodies")


if __name__ == "__main__":
    seed()
